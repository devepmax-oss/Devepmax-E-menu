import { deflateRawSync } from 'node:zlib';

/**
 * Libro de Excel (.xlsx) sin dependencias: hojas con encabezado en negrita y congelado,
 * números como números (para sumar y graficar en Excel) y montos con formato de dinero.
 */
export type Cell = string | number | null | undefined | { money: number } | { percent: number };

export interface Sheet {
  name: string;
  rows: Cell[][];
  /** Ancho de cada columna en caracteres. */
  widths?: number[];
}

const escapeXml = (s: string) =>
  s
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '')
    .replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' })[c]!);

/** 0 → A, 25 → Z, 26 → AA… */
export function columnName(index: number): string {
  let n = index + 1;
  let name = '';
  while (n > 0) {
    const r = (n - 1) % 26;
    name = String.fromCharCode(65 + r) + name;
    n = Math.floor((n - 1) / 26);
  }
  return name;
}

/** Excel no admite ciertos caracteres ni más de 31 letras en el nombre de una hoja. */
function sheetName(name: string, used: Set<string>): string {
  let base = name.replace(/[[\]:*?/\\]/g, ' ').trim().slice(0, 31) || 'Hoja';
  let candidate = base;
  for (let i = 2; used.has(candidate.toLowerCase()); i++) candidate = `${base.slice(0, 28)} ${i}`;
  used.add(candidate.toLowerCase());
  return candidate;
}

// Estilos: 0 normal · 1 negrita · 2 dinero · 3 negrita + dinero · 4 porcentaje · 5 negrita + porcentaje
function cellXml(ref: string, cell: Cell, header: boolean): string {
  if (cell === null || cell === undefined || cell === '') return '';
  if (typeof cell === 'number') {
    return Number.isFinite(cell) ? `<c r="${ref}"${header ? ' s="1"' : ''}><v>${cell}</v></c>` : '';
  }
  if (typeof cell === 'object' && 'money' in cell) {
    return Number.isFinite(cell.money) ? `<c r="${ref}" s="${header ? 3 : 2}"><v>${cell.money}</v></c>` : '';
  }
  if (typeof cell === 'object' && 'percent' in cell) {
    return Number.isFinite(cell.percent) ? `<c r="${ref}" s="${header ? 5 : 4}"><v>${cell.percent}</v></c>` : '';
  }
  return `<c r="${ref}" t="inlineStr"${header ? ' s="1"' : ''}><is><t xml:space="preserve">${escapeXml(String(cell))}</t></is></c>`;
}

function sheetXml(sheet: Sheet): string {
  const cols = sheet.widths?.length
    ? `<cols>${sheet.widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>`
    : '';
  const rows = sheet.rows
    .map((row, r) => `<row r="${r + 1}">${row.map((cell, c) => cellXml(`${columnName(c)}${r + 1}`, cell, r === 0)).join('')}</row>`)
    .join('');
  return (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">' +
    '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>' +
    cols +
    `<sheetData>${rows}</sheetData>` +
    '</worksheet>'
  );
}

